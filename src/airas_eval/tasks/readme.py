"""Generate the per-area task READMEs from the live registry.

Run ``python -m airas_eval.tasks.readme`` after changing any task or bundle;
``tests/test_tasks_readme.py`` fails if a README is stale. The READMEs are
derived, never hand-written, for the same reason the signature is.
"""

from pathlib import Path

from airas_eval.spec import TaskSpec
from airas_eval.tasks import AREAS

_HERE = Path(__file__).parent


def render_task(task: TaskSpec) -> str:
    lines = [f"### `{task.task_type}`", "", f"Signature: `{task.signature()}`", ""]
    if task.description:
        lines += [" ".join(task.description.split()), ""]
    if task.notes:
        lines += [task.notes, ""]
    for group in task.groups:
        bundle = group.bundle
        if len(task.groups) > 1 or group.name != "main":
            kind = "required" if group.required else "optional"
            lines += [f"**Group `{group.name}`** ({kind})", ""]
        req = ", ".join(f"`{n}`" for n in bundle.required_inputs()) or "—"
        opt = ", ".join(f"`{n}`" for n in bundle.optional_inputs()) or "—"
        lines += [f"- Required inputs: {req}", f"- Optional inputs: {opt}", ""]
        if bundle.notes:
            lines += [f"Conventions: {bundle.notes}.", ""]
        lines += ["| Metric | Function | Pinned |", "|---|---|---|"]
        for kind, bindings in (
            ("", bundle.metrics),
            (" (curve)", bundle.curves),
            (" (summary)", bundle.summary),
        ):
            for b in bindings:
                pinned = ", ".join(f"{k}={v!r}" for k, v in sorted(b.kwargs.items()))
                lines.append(
                    f"| `{group.name}.{b.name}`{kind} | `{b.fn.__module__}."
                    f"{b.fn.__qualname__}` | {pinned or '—'} |"
                )
        lines.append("")
    return "\n".join(lines)


def render_area(area: str, tasks: tuple[TaskSpec, ...]) -> str:
    head = [
        f"# Tasks: `{area}`",
        "",
        "<!-- GENERATED by `python -m airas_eval.tasks.readme` — do not edit. -->",
        "",
        "Every task returns *all* the metrics listed for it; nothing here is",
        "optional at call time. `airas-eval list <task_type>` prints the same",
        "from the installed package. *Scalar* and *curve* entries are both",
        "metrics (they differ only in shape); *summary* entries are input sizes,",
        "not metrics.",
        "",
        "| Task type | Scalar metrics | Curve metrics | Summary |",
        "|---|---|---|---|",
    ]
    for t in tasks:
        m = sum(len(g.bundle.metrics) for g in t.groups)
        c = sum(len(g.bundle.curves) for g in t.groups)
        s = sum(len(g.bundle.summary) for g in t.groups)
        head.append(
            f"| [`{t.task_type}`](#{t.task_type.replace('_', '')}) | {m} | {c} | {s} |"
        )
    head.append("")
    return "\n".join(head) + "\n" + "\n".join(render_task(t) for t in tasks)


def readme_path(area: str) -> Path:
    return _HERE / area / "README.md"


def main() -> None:
    for area, tasks in AREAS.items():
        readme_path(area).write_text(render_area(area, tasks))
        print(f"wrote {readme_path(area)}")


if __name__ == "__main__":
    main()
