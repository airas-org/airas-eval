"""登録済みタスクから、エリアごとの README を生成する。

タスクやバンドルを変更したら ``python -m airas_eval.tasks.readme`` を実行する。
``tests/test_tasks_readme.py`` は README が古いと失敗する。署名と同じ理由で、
README は手書きせず必ず宣言から導出する。
"""

import unicodedata
from pathlib import Path

from airas_eval.spec import TaskSpec
from airas_eval.tasks import AREAS

_HERE = Path(__file__).parent


def _is_wide(char: str) -> bool:
    return unicodedata.east_asian_width(char) in ("W", "F")


def _unwrap(text: str) -> str:
    """Join wrapped docstring lines: no space between CJK characters, one
    space otherwise (so English words at a line break stay separated)."""
    words = text.split()
    out = words[:1]
    for word in words[1:]:
        if _is_wide(out[-1][-1]) or _is_wide(word[0]):
            out[-1] += word
        else:
            out.append(word)
    return " ".join(out)


def render_task(task: TaskSpec) -> str:
    lines = [f"### `{task.task_type}`", "", f"署名: `{task.signature()}`", ""]
    if task.description:
        lines += [_unwrap(task.description), ""]
    if task.notes:
        lines += [task.notes, ""]
    for group in task.groups:
        bundle = group.bundle
        if len(task.groups) > 1 or group.name != "main":
            kind = "必須" if group.required else "任意"
            lines += [f"**グループ `{group.name}`**({kind})", ""]
        req = ", ".join(f"`{n}`" for n in bundle.required_inputs()) or "—"
        opt = ", ".join(f"`{n}`" for n in bundle.optional_inputs()) or "—"
        lines += [f"- 必須入力: {req}", f"- 任意入力: {opt}", ""]
        if bundle.notes:
            lines += [f"規約: {bundle.notes}。", ""]
        lines += ["| 指標 | 説明 | 実装 | 固定パラメータ |", "|---|---|---|---|"]
        for kind, bindings in (("", bundle.metrics), ("(曲線)", bundle.curves)):
            for b in bindings:
                pinned = ", ".join(f"{k}={v!r}" for k, v in sorted(b.kwargs.items()))
                lines.append(
                    f"| `{group.name}.{b.name}`{kind} | {b.description} | "
                    f"`{b.fn.__module__}.{b.fn.__qualname__}` | {pinned or '—'} |"
                )
        lines.append("")
        if bundle.summary:
            lines += ["入力サイズ(指標ではない):", ""]
            lines += [
                f"- `{group.name}.{b.name}` — {b.description}" for b in bundle.summary
            ]
            lines.append("")
    return "\n".join(lines)


def render_area(area: str, tasks: tuple[TaskSpec, ...]) -> str:
    head = [
        f"# タスク: `{area}`",
        "",
        "<!-- GENERATED by `python -m airas_eval.tasks.readme` — 編集しないこと -->",
        "",
        "各タスクは、ここに列挙された指標を**すべて**返す。呼び出し時に選べるものは",
        "ない。`airas-eval list <task_type>` はインストール済みパッケージから同じ",
        "内容を表示する。スカラーと曲線はどちらも指標で、形が違うだけである。",
        "入力サイズ(`n_*`, `total_*`)は `inputs_summary` に報告され、各表の下に",
        "別掲する。",
        "",
        "| タスクタイプ | 指標数 | うち曲線 |",
        "|---|---|---|",
    ]
    for t in tasks:
        m = sum(len(g.bundle.metrics) + len(g.bundle.curves) for g in t.groups)
        c = sum(len(g.bundle.curves) for g in t.groups)
        head.append(
            f"| [`{t.task_type}`](#{t.task_type.replace('_', '')}) | {m} | {c} |"
        )
    head.append("")
    return "\n".join(head) + "\n" + "\n".join(render_task(t) for t in tasks)


def readme_path(area: str) -> Path:
    return _HERE / area / "README.md"


def main() -> None:
    for area, tasks in AREAS.items():
        readme_path(area).write_text(render_area(area, tasks))
        print(f"wrote {readme_path(area)}")


if __name__ == "__main__":
    main()
