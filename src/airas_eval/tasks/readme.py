"""登録済みタスクから、エリアごとの README を生成する。

タスクや指標セットを変更したら ``python -m airas_eval.tasks.readme`` を実行する。
``tests/test_tasks_readme.py`` は README が古いと失敗する。署名と同じ理由で、
README は手書きせず必ず宣言から導出する。
"""

from pathlib import Path

from airas_eval.spec import TaskSpec, unwrap_text
from airas_eval.tasks import AREAS

_HERE = Path(__file__).parent


def render_task(task: TaskSpec) -> str:
    lines = [f"### `{task.task_type}`", "", f"署名: `{task.signature()}`", ""]
    if task.description:
        lines += [unwrap_text(task.description), ""]
    if task.notes:
        lines += [f"規約: {task.notes}。", ""]
    lines += ["| 入力 | 説明 |", "|---|---|"]
    for i in task.input_fields():
        marker = "" if i["required"] else "?"
        lines.append(f"| `{i['name']}{marker}: {i['type']}` | {i['description']} |")
    lines.append("")
    lines += [
        "| 指標 | 値域 | 良い方向 | 説明 | 実装 | 固定パラメータ |",
        "|---|---|---|---|---|---|",
    ]
    arrows = {"higher": "高いほど良い", "lower": "低いほど良い", "none": "—"}
    for kind, bindings in (("", task.metrics), ("(曲線)", task.curves)):
        for b in bindings:
            pinned = ", ".join(f"{k}={v!r}" for k, v in sorted(b.kwargs.items()))
            lines.append(
                f"| `{b.name}`{kind} | {b.value_range} | {arrows[b.direction]} | "
                f"{b.description} | `{b.fn.__module__}.{b.fn.__qualname__}` | "
                f"{pinned or '—'} |"
            )
    lines.append("")
    if task.summary:
        lines += ["入力サイズ(指標ではない):", ""]
        lines += [f"- `{b.name}` — {b.description}" for b in task.summary]
        lines.append("")
    if task.per_example:
        lines += ["事例ごとのスコア(`compare` 用、指標ではない):", ""]
        lines += [f"- `{b.name}` — {b.description}" for b in task.per_example]
        lines.append("")
    return "\n".join(lines)


def render_area(area: str, tasks: tuple[TaskSpec, ...]) -> str:
    head = [
        f"# タスク: `{area}`",
        "",
        "<!-- GENERATED by `python -m airas_eval.tasks.readme` — 編集しないこと -->",
        "",
        "各タスクは、ここに列挙された指標を**すべて**返す。呼び出し時に選べるものは",
        "ない。`airas-eval list <task_type>` はインストール済みパッケージから同じ",
        "内容を表示する。スカラーと曲線はどちらも指標で、形が違うだけである。",
        "入力サイズ(`n_*`, `total_*`)は `inputs_summary` に報告され、各表の下に",
        "別掲する。",
        "",
        "| タスクタイプ | 指標数 | うち曲線 |",
        "|---|---|---|",
    ]
    for t in tasks:
        m = len(t.metrics) + len(t.curves)
        c = len(t.curves)
        head.append(
            f"| [`{t.task_type}`](#{t.task_type.replace('_', '')}) | {m} | {c} |"
        )
    head.append("")
    return "\n".join(head) + "\n" + "\n".join(render_task(t) for t in tasks)


def readme_path(area: str) -> Path:
    return _HERE / area / "README.md"


def main() -> None:
    for area, tasks in AREAS.items():
        readme_path(area).write_text(render_area(area, tasks))
        print(f"wrote {readme_path(area)}")


if __name__ == "__main__":
    main()
